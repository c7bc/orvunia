import { readdir, lstat, realpath, readFile, mkdir, writeFile, rename, unlink } from "node:fs/promises";
import { resolve, dirname, basename } from "node:path";
import { createHash, randomUUID } from "node:crypto";

const relativeDirectory = "next/packages/desktop/system-audio";
const generatedSource = `${relativeDirectory}/resource-manifest.ts`;
const digest = data => createHash("sha256").update(data).digest("hex");
const serialized = value => JSON.stringify(value, null, 2) + "\n";
const generated = manifest => `// Generated by scripts/native-audio-resources.mjs. Review helper sources before regenerating.\n`
  + `export const systemAudioResourceManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`;

async function physicalFile(path) {
  const info = await lstat(path);
  if (!info.isFile() || info.isSymbolicLink() || await realpath(path) !== path || info.size > 64 * 1024)
    throw Error("Audio resources must be bounded physical source files");
  return readFile(path);
}

async function capture(sourceRoot) {
  const directory = resolve(sourceRoot, relativeDirectory);
  const names = (await readdir(directory)).filter(name => /\.(?:cs|ps1)$/.test(name)).sort();
  if (!names.includes("helper.ps1") || names.length < 2 || names.length > 32)
    throw Error("Native audio requires its bounded reviewed helper resources");
  const files = [], buffers = [];
  for (const name of names) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*\.(?:cs|ps1)$/.test(name)) throw Error("Invalid audio resource name");
    const data = await physicalFile(resolve(directory, name));
    const text = new TextDecoder("utf-8", { fatal: true }).decode(data);
    if (text.trimEnd().split(/\r?\n/).length > 200) throw Error("Audio resource exceeds 200 lines");
    files.push({ path: name, bytes: data.length, sha256: digest(data) });
    buffers.push(data);
  }
  return { sourceRoot: resolve(sourceRoot), manifest: { format: "orvunia-system-audio-resources/1", files }, buffers };
}

async function atomicWrite(path, data) {
  const directory = dirname(path);
  await mkdir(directory, { recursive: true });
  if (await realpath(directory) !== directory || (await lstat(directory)).isSymbolicLink())
    throw Error("Audio output must use a physical directory");
  const temporary = resolve(directory, `.${basename(path)}.${randomUUID()}.tmp`);
  try { await writeFile(temporary, data, { flag: "wx" }); await rename(temporary, path); }
  finally { await unlink(temporary).catch(error => { if (error.code !== "ENOENT") throw error; }); }
}

export async function generateNativeAudioResourceManifest(sourceRoot) {
  const snapshot = await capture(sourceRoot);
  const path = resolve(sourceRoot, generatedSource), text = generated(snapshot.manifest);
  const previous = await physicalFile(path).catch(error => { if (error.code !== "ENOENT") throw error; return null; });
  if (previous?.toString("utf8") !== text)
    await atomicWrite(path, text);
  await verifySnapshot(snapshot);
  return snapshot;
}

async function verifySnapshot(snapshot) {
  const current = await capture(snapshot.sourceRoot);
  if (serialized(current.manifest) !== serialized(snapshot.manifest))
    throw Error("Native audio resources changed during build; prepare the manifest again");
  const actual = await physicalFile(resolve(snapshot.sourceRoot, generatedSource));
  if (actual.toString("utf8") !== generated(snapshot.manifest))
    throw Error("Native audio resource manifest is stale; generate it before assembling the source package");
  for (const [index, file] of snapshot.manifest.files.entries())
    if (snapshot.buffers[index].length !== file.bytes || digest(snapshot.buffers[index]) !== file.sha256)
      throw Error("Captured native audio resource bytes do not match their manifest");
}

export async function verifyNativeAudioResourceManifest(sourceRoot) {
  const snapshot = await capture(sourceRoot);
  await verifySnapshot(snapshot);
  return snapshot;
}

export async function verifyCopiedNativeAudioResources(destinationRoot, expected) {
  const directory = resolve(destinationRoot, "desktop/system-audio");
  const entries = await readdir(directory, { withFileTypes: true });
  const approved = new Set(["manifest.json", ...expected.files.map(file => file.path)]);
  if (entries.length !== approved.size || entries.some(entry =>
    !approved.has(entry.name) || !entry.isFile() || entry.isSymbolicLink()))
    throw Error("Copied native audio directory contains unexpected resources");
  const actual = JSON.parse(await physicalFile(resolve(directory, "manifest.json")));
  if (serialized(actual) !== serialized(expected)) throw Error("Copied native audio audit manifest does not match embedded hashes");
  for (const file of expected.files) {
    const data = await physicalFile(resolve(directory, file.path));
    if (data.length !== file.bytes || digest(data) !== file.sha256)
      throw Error("Copied native audio resources do not match embedded hashes");
  }
}

export async function copyNativeAudioResources(sourceRoot, destinationRoot, providedSnapshot) {
  const snapshot = providedSnapshot ?? await verifyNativeAudioResourceManifest(sourceRoot);
  if (snapshot.sourceRoot !== resolve(sourceRoot)) throw Error("Audio resource snapshot belongs to another source root");
  await verifySnapshot(snapshot);
  const sources = [...snapshot.manifest.files.map(file => `${relativeDirectory}/${file.path}`), generatedSource];
  const bundles = [];
  for (const [index, file] of snapshot.manifest.files.entries()) {
    const path = `desktop/system-audio/${file.path}`;
    await atomicWrite(resolve(destinationRoot, path), snapshot.buffers[index]);
    bundles.push(path);
  }
  const path = "desktop/system-audio/manifest.json";
  await atomicWrite(resolve(destinationRoot, path), serialized(snapshot.manifest));
  bundles.push(path);
  await verifySnapshot(snapshot);
  await verifyCopiedNativeAudioResources(destinationRoot, snapshot.manifest);
  return { sources, bundles, manifest: snapshot.manifest };
}
