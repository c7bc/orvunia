export type BenchmarkState = "queued" | "running" | "cancelling" | "completed" | "failed" | "cancelled";
export type BenchmarkMeasurementCounts = { timeToFirstToken: number; tokensPerSecond: number; residentMemory: number; vram: number };
export type BenchmarkAggregation = { timeToFirstToken: "mean-measured-cases"; tokensPerSecond: "sum-tokens-over-sum-generation-time";
  residentMemory: "max-sampled-owned-process"; vram: "max-measured-cases" };
export type BenchmarkTelemetry = { timeToFirstTokenMilliseconds: number | null; tokensPerSecond: number | null;
  residentMemoryBytes: number | null; vramBytes: number | null; generatedTokens: number | null;
  generationMilliseconds: number | null; memorySamples: number;
  provenance: { timeToFirstToken: string | null; tokensPerSecond: string | null; residentMemory: string | null; vram: string | null };
  unavailableReasons: string[] };
export type BenchmarkCase = { capability: "text" | "vision" | "transcription"; language: "pt" | "en" | "es" | null;
  fixtureId: string; fixtureSha256: string; latencyMilliseconds: number; output: string; outputTruncated: boolean;
  reference: string; quality: { passed: boolean; metric: "exact-array" | "wer"; value: number; maximum: number;
    criticalTermsPreserved: boolean | null }; telemetry?: BenchmarkTelemetry };
export type BenchmarkRun = { id: string; requestId: string; installationId: string; state: BenchmarkState;
  revision: number; createdAt: number; startedAt: number | null; finishedAt: number | null;
  snapshot: { manifest: { id: string; name: string; revision: string; quantization: string };
    runtime: { kind: "llama.cpp" | "whisper.cpp"; version: string; sha256: string };
    settings: { contextTokens: number; maximumOutputTokens: number; threads: number }; fixtureVersion: string };
  result: null | { warmupMilliseconds: number | null; cases: BenchmarkCase[]; timeToFirstTokenMilliseconds: number | null;
    tokensPerSecond: number | null; residentMemoryBytes: number | null; vramBytes: number | null; unavailableReasons: string[];
    measurementCounts?: BenchmarkMeasurementCounts; aggregation?: BenchmarkAggregation };
  error: null | { code: string } };
export type BenchmarkView = { histories: Record<string, BenchmarkRun[]>; confirming: string | null; error: string };
export const activeBenchmark = (run: BenchmarkRun) => ["queued", "running", "cancelling"].includes(run.state);
